set name_variants = array(select distinct v from unnest(coalesce(a.name_variants, '{}') || nv.variant) v),
    updated_at = now()
from (values
  (195,  'צורן קדימה'),
  (5540, 'שדות דן-עמק לוד'),
  (1770, 'רמת חובב'),
  (5527, 'גן רוה'),
