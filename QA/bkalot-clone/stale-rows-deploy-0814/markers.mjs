// המסומנים של a3a3405, במקום אחד, כדי שהבדיקה המקומית וה-HTTP ימדדו בדיוק את
// אותו דבר. הפיצול לשלוש רשימות הוא העיקר:
//
// NEW     — חייבים להיות false בגרסה שבייצור ו-true אחרי. אלה שקונים את הפעימה.
// REMOVED — ההפך: true לפני, false אחרי. בלעדיהם «נפרס» יכול להיות גם «נפרסו
//           שתי הגרסאות זו על גבי זו», וזה בדיוק מה ששני קבצים באותו גודל
//           נראים כמו.
// OLD     — true בשתי הגרסאות. אלה אינם ראיה לפעימה אלא בקרת רגרסיה: פריסה
//           מ-dist ישן מחזירה מסכים אחורה בלי ששום דבר ידווח שגיאה.
//
// הקושי כאן הפוך מזה של e12acf9: שם המחרוזת שקונה את הפעימה הייתה כבר בייצור
// והמלכודת הייתה לקרוא OLD כ-NEW. כאן a3a3405 הוא **תוספת טהורה** — שלוש שורות
// קוד ותשע שורות הסבר, ולא נמחקה ולו שורה אחת. לכן אין מחרוזת שנעלמה, ו-REMOVED
// לא יכול להיות מחרוזת: הוא חייב להיות **סמיכות**. לפני התוספת השורה שאחרי
// toLogin הייתה מיד המונה, ואחריה חוצצות ביניהן שתים-עשרה שורות. זה מה שנמדד,
// והוא ניתן להפרכה בדיוק כמו מחרוזת שנמחקה.
//
// שלושת מסומני ה-NEW הם קוד ולא הסבר, ושלושתם נבדקו כמופע יחיד בקובץ:
// `$("empty").hidden = true` מול `= cases.length > 0` בנתיב ההצלחה,
// ו-`$("pager").hidden = true` מול `= total <= PAGE`. מסומן שמופיע פעמיים היה
// מחזיר true על הגרסה שבייצור בזכות המופע האחר.
export const NEW = [
  '$("rows").innerHTML = "";',
  '$("empty").hidden = true;',
  '$("pager").hidden = true;',
  "«לא ידוע» אינו «אין»",
];

// סמיכות ולא מחרוזת — ראה ההסבר למעלה.
export const REMOVED = [
  'toLogin(data.error);\n      $("count").textContent = "—";',
];

export const OLD = [
  'if (data?.expired) return toLogin(data.error);',
  '$("count").textContent = "—";',
  'showError($("list-error"), data?.error || "bad_response");',
  '$("empty").hidden = cases.length > 0;',
  '$("pager").hidden = total <= PAGE;',
  "אין פניות שתואמות את הסינון",
  "זכות אחת",
  "מסמך אחד",
  "כל הרשימה",
  "נוסח נפילה",
  "לא הוכרע מהמסך",
  "<th>מכתב</th>",
  "הכנס לתור",
  "עבד עכשיו",
];

export const report = (t) => ({
  new: NEW.map((m) => JSON.stringify(m) + "=" + t.includes(m)).join(" | "),
  removed: REMOVED.map((m) => JSON.stringify(m) + "=" + t.includes(m)).join(" | "),
  old: OLD.map((m) => JSON.stringify(m) + "=" + t.includes(m)).join(" | "),
});
